import { test } from "node:test";
import assert from "node:assert/strict";
import { applyEvent, emptyChat } from "../../shared/chat-state";
import type { SnapshotEvent } from "@earendil-works/pi-durable";

test("stream renders text deltas, bounded tool output, failures and authoritative reconnect snapshots", () => {
  let state = applyEvent(emptyChat, { type: "run_start", inputs: [] });
  state = applyEvent(state, { type: "message_update", usage: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, totalTokens: 0, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 } }, changes: [{ type: "text_delta", contentIndex: 0, delta: "Hello " }, { type: "text_delta", contentIndex: 0, delta: "team" }] });
  assert.equal(state.partial, "Hello team");
  assert.equal(state.running, true);
  state = applyEvent(state, { type: "tool_execution_start", toolCallId: "call", toolName: "sandbox", args: {} });
  state = applyEvent(state, { type: "tool_execution_update", toolCallId: "call", toolName: "sandbox", output: { set: "old output" } });
  state = applyEvent(state, { type: "tool_execution_update", toolCallId: "call", toolName: "sandbox", output: { trimStart: 4, append: " done" } });
  assert.equal(state.tools.call.output, "output done");
  state = applyEvent(state, { type: "tool_execution_end", toolCallId: "call", toolName: "sandbox" });
  assert.equal(state.tools.call.done, true);
  state = applyEvent(state, { type: "auto_retry_start", attempt: 1, at: 123, errorMessage: "provider unavailable" });
  assert.equal(state.status, "Retrying: provider unavailable");
  state = applyEvent(state, { type: "task_failed", taskId: "failed", kind: "generation", message: "model unavailable" });
  assert.equal(state.status, "Unanswered: model unavailable");
  const stale: SnapshotEvent["entries"][number] = { id: 1 as SnapshotEvent["entries"][number]["id"], conversationId: 0 as SnapshotEvent["entries"][number]["conversationId"], kind: "message", model: [{ role: "user", content: "Stale transcript", timestamp: 1 }] };
  const fresh: SnapshotEvent["entries"][number] = { ...stale, id: 2 as SnapshotEvent["entries"][number]["id"], model: [{ role: "user", content: "Authoritative transcript", timestamp: 2 }] };
  state = applyEvent(state, { type: "entry_appended", entry: stale });
  assert.deepEqual(state.entries, [stale]);
  const snapshot: SnapshotEvent = { type: "snapshot", entries: [fresh], tools: [{ callId: "fresh", name: "read", status: "running", output: "restored" }], nestedTools: [], compactions: [], inbox: [], agent: {}, usage: { models: {}, tools: {} } };
  state = applyEvent(state, snapshot);
  assert.deepEqual(state.entries, [fresh], "Reconnect must replace stale transcript, not retain or append it");
  state = applyEvent(state, snapshot);
  assert.deepEqual(state.entries, [fresh], "Repeated snapshots must not duplicate transcript entries");
  assert.equal(state.partial, "");
  assert.equal(state.running, false);
  assert.equal(state.status, "Ready");
  assert.deepEqual(state.tools, { fresh: { name: "read", output: "restored", done: false } });
});
